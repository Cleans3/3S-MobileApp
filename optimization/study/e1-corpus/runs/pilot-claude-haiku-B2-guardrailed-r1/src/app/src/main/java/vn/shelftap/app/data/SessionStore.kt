package vn.shelftap.app.data

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import org.json.JSONException
import org.json.JSONObject
import java.io.File
import java.nio.BufferUnderflowException
import java.nio.ByteBuffer
import java.nio.file.Files
import java.nio.file.StandardCopyOption
import java.security.GeneralSecurityException
import java.security.KeyStore
import java.util.UUID
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

data class Tokens(val accessToken: String, val refreshToken: String)

/**
 * Holds the installation's deviceId and the member's session tokens.
 *
 * Everything is written as one AES-256-GCM ciphertext file in app-private storage.
 * The key is created inside the Android Keystore and cannot be exported. Each write
 * uses a fresh IV generated by the Cipher. Backups are disabled in the manifest, so the
 * file never leaves the device without its key.
 */
class SessionStore(context: Context) {

    private val file = File(context.filesDir, FILE_NAME)
    private val lock = Any()

    /** Returns the deviceId, creating and storing a UUID on first use. */
    fun deviceId(): String = synchronized(lock) {
        val state = readState()
        state.deviceId ?: UUID.randomUUID().toString().also { id ->
            writeState(state.copy(deviceId = id))
        }
    }

    fun tokens(): Tokens? = synchronized(lock) {
        val state = readState()
        val access = state.accessToken
        val refresh = state.refreshToken
        if (access != null && refresh != null) Tokens(access, refresh) else null
    }

    fun saveTokens(tokens: Tokens): Unit = synchronized(lock) {
        writeState(readState().copy(accessToken = tokens.accessToken, refreshToken = tokens.refreshToken))
    }

    /** Removes the session. The deviceId is kept for the life of the installation. */
    fun clearTokens(): Unit = synchronized(lock) {
        writeState(readState().copy(accessToken = null, refreshToken = null))
    }

    private data class StoredState(
        val deviceId: String? = null,
        val accessToken: String? = null,
        val refreshToken: String? = null,
    )

    private fun readState(): StoredState {
        if (!file.exists()) return StoredState()
        return try {
            val json = JSONObject(String(decrypt(file.readBytes()), Charsets.UTF_8))
            StoredState(
                deviceId = json.optString("deviceId").ifEmpty { null },
                accessToken = json.optString("accessToken").ifEmpty { null },
                refreshToken = json.optString("refreshToken").ifEmpty { null },
            )
        } catch (e: GeneralSecurityException) {
            // The Keystore key is gone or the file is damaged: treat as no session.
            file.delete()
            StoredState()
        } catch (e: JSONException) {
            file.delete()
            StoredState()
        } catch (e: BufferUnderflowException) {
            file.delete()
            StoredState()
        }
    }

    private fun writeState(state: StoredState) {
        val json = JSONObject()
            .put("deviceId", state.deviceId ?: "")
            .put("accessToken", state.accessToken ?: "")
            .put("refreshToken", state.refreshToken ?: "")
        val sealed = encrypt(json.toString().toByteArray(Charsets.UTF_8))
        val tmp = File(file.parentFile, "$FILE_NAME.tmp")
        tmp.writeBytes(sealed)
        Files.move(tmp.toPath(), file.toPath(), StandardCopyOption.ATOMIC_MOVE)
    }

    /** Output layout: [1 byte IV length][IV][ciphertext with GCM tag]. */
    private fun encrypt(plain: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey())
        val iv = cipher.iv
        val cipherText = cipher.doFinal(plain)
        return ByteBuffer.allocate(1 + iv.size + cipherText.size)
            .put(iv.size.toByte())
            .put(iv)
            .put(cipherText)
            .array()
    }

    private fun decrypt(sealed: ByteArray): ByteArray {
        val buffer = ByteBuffer.wrap(sealed)
        val iv = ByteArray(buffer.get().toInt() and 0xFF)
        buffer.get(iv)
        val cipherText = ByteArray(buffer.remaining())
        buffer.get(cipherText)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, secretKey(), GCMParameterSpec(GCM_TAG_BITS, iv))
        return cipher.doFinal(cipherText)
    }

    private fun secretKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        (keyStore.getKey(KEY_ALIAS, null) as? SecretKey)?.let { return it }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setKeySize(256)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setRandomizedEncryptionRequired(true)
                .build(),
        )
        return generator.generateKey()
    }

    private companion object {
        const val FILE_NAME = "session.bin"
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val KEY_ALIAS = "shelftap_session_aes256"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val GCM_TAG_BITS = 128
    }
}
