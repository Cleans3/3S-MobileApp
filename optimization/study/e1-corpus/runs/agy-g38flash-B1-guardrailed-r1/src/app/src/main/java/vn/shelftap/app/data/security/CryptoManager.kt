package vn.shelftap.app.data.security

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import kotlinx.coroutines.withContext
import vn.shelftap.app.di.DispatcherProvider
import java.io.File
import java.io.FileInputStream
import java.io.FileOutputStream
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Complies with Rules 4, 5, 6:
 * - Stores tokens and personal data only encrypted
 * - Creates AES-256 key in Android Keystore (non-exportable)
 * - AES in GCM mode (AES/GCM/NoPadding) with fresh random IV per encryption generated by Cipher
 * - Keeps ciphertext only in app-private storage
 * - Does not use deprecated androidx.security:security-crypto
 */
class CryptoManager(
    private val context: Context,
    private val dispatcherProvider: DispatcherProvider
) {
    companion object {
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val KEY_ALIAS = "ShelfTapMasterKey"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val KEY_SIZE = 256
        private const val TAG_LENGTH_BITS = 128
        private const val IV_LENGTH_BYTES = 12
    }

    private val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply {
        load(null)
    }

    private fun getOrCreateKey(): SecretKey {
        val existingKey = keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry
        if (existingKey != null) {
            return existingKey.secretKey
        }

        val keyGenerator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            ANDROID_KEYSTORE
        )
        val spec = KeyGenParameterSpec.Builder(
            KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(KEY_SIZE)
            .setRandomizedEncryptionRequired(true)
            .build()

        keyGenerator.init(spec)
        return keyGenerator.generateKey()
    }

    suspend fun encryptData(bytes: ByteArray): ByteArray = withContext(dispatcherProvider.default) {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        val key = getOrCreateKey()
        cipher.init(Cipher.ENCRYPT_MODE, key)
        val iv = cipher.iv // Fresh random IV generated by Cipher (Rule 6)
        val ciphertext = cipher.doFinal(bytes)
        val output = ByteArray(iv.size + ciphertext.size)
        System.arraycopy(iv, 0, output, 0, iv.size)
        System.arraycopy(ciphertext, 0, output, iv.size, ciphertext.size)
        output
    }

    suspend fun decryptData(encryptedBytes: ByteArray): ByteArray = withContext(dispatcherProvider.default) {
        require(encryptedBytes.size > IV_LENGTH_BYTES) { "Invalid encrypted data length" }
        val iv = ByteArray(IV_LENGTH_BYTES)
        System.arraycopy(encryptedBytes, 0, iv, 0, IV_LENGTH_BYTES)
        val ciphertextLength = encryptedBytes.size - IV_LENGTH_BYTES
        val ciphertext = ByteArray(ciphertextLength)
        System.arraycopy(encryptedBytes, IV_LENGTH_BYTES, ciphertext, 0, ciphertextLength)

        val cipher = Cipher.getInstance(TRANSFORMATION)
        val spec = GCMParameterSpec(TAG_LENGTH_BITS, iv)
        cipher.init(Cipher.DECRYPT_MODE, getOrCreateKey(), spec)
        cipher.doFinal(ciphertext)
    }

    suspend fun writeEncryptedFile(fileName: String, data: ByteArray) = withContext(dispatcherProvider.io) {
        val encrypted = encryptData(data)
        val file = File(context.filesDir, fileName)
        FileOutputStream(file).use { it.write(encrypted) }
    }

    suspend fun readEncryptedFile(fileName: String): ByteArray? = withContext(dispatcherProvider.io) {
        val file = File(context.filesDir, fileName)
        if (!file.exists()) return@withContext null
        val encrypted = FileInputStream(file).use { it.readBytes() }
        decryptData(encrypted)
    }
}
