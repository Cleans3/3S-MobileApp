#!/usr/bin/env python3
"""E5 analysis (stdlib): pooled issue-level proportions with Wilson 95% CIs, rep-level paired sign-flip permutation tests (evidence vs none), cost per level.
  analyze_e5.py  -> results/summary.csv, results/stats.md
"""
import csv, itertools, math, pathlib, statistics
from collections import defaultdict

E5 = pathlib.Path(__file__).resolve().parent.parent
R = E5 / "results"
N_SEEDED = 14

def rows(p): return list(csv.DictReader(open(R / p))) if (R / p).exists() else []
def f(x): return float(x) if x not in ("", None) else 0.0

def wilson(k, n, z=1.959964):
    if n == 0: return (float("nan"),) * 3
    p = k / n; d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, max(0, c - h), min(1, c + h)

def signflip_p(diffs):
    """two-sided exact paired sign-flip permutation test on per-pair differences"""
    n = len(diffs); obs = abs(sum(diffs))
    if n == 0 or all(d == 0 for d in diffs): return 1.0
    hit = sum(1 for s in itertools.product((1, -1), repeat=n) if abs(sum(si * d for si, d in zip(s, diffs))) >= obs - 1e-12)
    return hit / 2 ** n

def main():
    allruns = rows("runs.csv"); finds = rows("findings.csv")
    # A11 (agy OAuth died 2026-11-21): E5 fixer bundles = codex + claude-haiku; the agy rows that exist are descriptive and never pooled
    runs = [r for r in allruns if r["status"] == "ok" and r["tool"] != "agy"]  # harness halts and their dependent approve rows are listed, not scored
    excluded = [r for r in allruns if r["status"] != "ok" and r["tool"] != "agy"]
    agy_rows = [r for r in allruns if r["tool"] == "agy"]
    out, md = [], ["# E5 statistics (generated by harness/analyze_e5.py)", ""]
    def add(**kw): out.append(kw)
    cells = defaultdict(list)
    for r in runs: cells[(r["tool"], r["arm"], r["level"])].append(r)
    md += ["## Per cell (pooled over reps; Wilson 95% CI on issue-level proportions)", "", "| tool | evidence arm | level | reps | seeded issues found/fixed (of 14 per rep) | precision of reports (tp/reported) | claim precision (correct/claimed) | reps with regression | reps with extra weakening | invocations (mean) | tokens in+out (mean) | seconds (mean) |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for (tool, arm, level), rs in sorted(cells.items()):
        n = len(rs)
        if level == "advice":
            k = sum(round(f(r["recall_seeded"]) * N_SEEDED) for r in rs); p1 = wilson(k, N_SEEDED * n)
            tp = sum(f(r["tp"]) for r in rs); rep = sum(f(r["reported"]) for r in rs); p2 = wilson(tp, rep)
            a, b = f"{k}/{N_SEEDED*n} = {p1[0]:.2f} ({p1[1]:.2f}-{p1[2]:.2f})", f"{int(tp)}/{int(rep)} = {p2[0]:.2f} ({p2[1]:.2f}-{p2[2]:.2f})"; c = "-"
            add(tool=tool, arm=arm, level=level, n_reps=n, metric="recall_seeded", k=k, n=N_SEEDED * n, share=round(p1[0], 3), ci_lo=round(p1[1], 3), ci_hi=round(p1[2], 3))
            add(tool=tool, arm=arm, level=level, n_reps=n, metric="precision_reports", k=int(tp), n=int(rep), share=round(p2[0], 3), ci_lo=round(p2[1], 3), ci_hi=round(p2[2], 3))
        else:
            k = int(sum(f(r["fixed_seeded"]) for r in rs)); p1 = wilson(k, N_SEEDED * n)
            a = f"{k}/{N_SEEDED*n} = {p1[0]:.2f} ({p1[1]:.2f}-{p1[2]:.2f})"; b = "-"
            add(tool=tool, arm=arm, level=level, n_reps=n, metric="fixed_seeded", k=k, n=N_SEEDED * n, share=round(p1[0], 3), ci_lo=round(p1[1], 3), ci_hi=round(p1[2], 3))
            cl, cc = sum(f(r["claimed_fixed"]) for r in rs), sum(f(r["claim_correct"]) for r in rs)
            c = f"{int(cc)}/{int(cl)}" if level == "autonomous" and cl else "-"
        reg = sum(1 for r in rs if r["regressions"] or r["extra_weakenings"] and False); xw = sum(1 for r in rs if r["extra_weakenings"])
        md.append(f"| {tool} | {arm} | {level} | {n} | {a} | {b} | {c} | {sum(1 for r in rs if r['regressions'])}/{n} | {xw}/{n} | {statistics.mean(f(r['invocations']) for r in rs):.1f} | {statistics.mean(f(r['tokens_in']) + f(r['tokens_out']) for r in rs):.0f} | {statistics.mean(f(r['duration_s']) for r in rs):.0f} |")
    md += ["", "## Evidence vs no evidence (paired by tool and rep; exact two-sided sign-flip permutation test on the per-rep difference)", "", "| level | metric | n pairs | mean diff (evidence - none) | p |", "|---|---|---|---|---|"]
    for level, key, scale in (("advice", "recall_seeded", 1), ("autonomous", "fixed_seeded", 1 / N_SEEDED), ("approve", "fixed_seeded", 1 / N_SEEDED)):
        by = {(r["tool"], r["rep"], r["arm"]): f(r[key]) * scale for r in runs if r["level"] == level}
        pairs = [(by[(t, rep, "evidence")], by[(t, rep, "none")]) for (t, rep, arm) in by if arm == "none" and (t, rep, "evidence") in by]
        d = [a - b for a, b in pairs]
        if d: md.append(f"| {level} | {key} | {len(d)} | {statistics.mean(d):+.3f} | {signflip_p(d):.3f} |"); add(tool="all", arm="evidence-none", level=level, n_reps=len(d), metric="paired_diff_" + key, k="", n=len(d), share=round(statistics.mean(d), 4), ci_lo="", ci_hi="")
    fp_ids = defaultdict(int); tp_ids = defaultdict(int)
    for r in finds: (fp_ids if r["triage"] == "fp" else tp_ids)[r["id"]] += 1
    md += ["", "## Reported ids that were false positives (all advice runs)", "", ", ".join(f"{k} x{v}" for k, v in sorted(fp_ids.items(), key=lambda kv: -kv[1])) or "none"]
    md += ["", "## agy rows (descriptive only, never pooled; agy auth expired before the planned cells finished, protocol A11)", "", "| seq | level | status | seeded found/fixed | tp/reported | regressions | compiles |", "|---|---|---|---|---|---|---|"]
    md += [f"| {r['seq']} | {r['level']} | {r['status']} | {r['recall_seeded'] if r['level'] == 'advice' else r['fixed_seeded']} | {r['tp']}/{r['reported']} | {r['regressions'] or '-'} | {r['compiles'] or '-'} |" for r in agy_rows] or ["| none | | | | | | |"]
    md += ["", "## Rows excluded from the scores (status not ok)", "", ", ".join(f"{r['seq']}/{r['level']}={r['status']}" for r in excluded) or "none"]
    cm = defaultdict(lambda: [0, 0])
    for r in runs:
        if r["level"] in ("autonomous", "approve") and r.get("compiles") in ("0", "1"): cm[(r["tool"], r["arm"], r["level"])][0] += int(r["compiles"]); cm[(r["tool"], r["arm"], r["level"])][1] += 1
    md += ["", "## Fixed trees that compile (:app:compileDebugKotlin) / fixed trees", "", "| tool | arm | level | compiling / reps |", "|---|---|---|---|"] + [f"| {k[0]} | {k[1]} | {k[2]} | {v[0]}/{v[1]} |" for k, v in sorted(cm.items())]
    (R / "stats.md").write_text("\n".join(md) + "\n")
    with open(R / "summary.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, ["tool", "arm", "level", "n_reps", "metric", "k", "n", "share", "ci_lo", "ci_hi"], lineterminator="\n"); w.writeheader(); w.writerows(out)
    print("\n".join(md[:12]))

if __name__ == "__main__":
    main()
