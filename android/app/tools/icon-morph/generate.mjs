// Build-time generator for the icon set and the icon morphs (plan §6.3). Run: npm ci && npm run generate
//
//  1. Reads Lucide SVGs (ISC) from node_modules/lucide-static and writes each as one canonical path string.
//  2. For each pair in icons.json builds a Morphicons plan (rotation, scale and translation interpolated separately,
//     not a straight blend of points), runs the spring preset at a fixed step until it settles, and samples the
//     result at evenly spaced *times*. The spring's easing is therefore baked into the keyframes; the app plays them
//     with a linear clock over the settle time.
//  3. Writes android/app/src/main/kotlin/shelftap/android/ui/icons/LucideIcons.kt. Do not edit that file by hand.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  Spring, SPRING_PRESETS, allocOutputs, buildPlan, cubicsToPathD, iconToCubics, interpPolar, resampleIcon,
} from 'morphicons';

const here = dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(join(here, 'icons.json'), 'utf8'));
const outFile = join(here, '../../src/main/kotlin/shelftap/android/ui/icons/LucideIcons.kt');
const lucideVersion = JSON.parse(readFileSync(join(here, 'node_modules/lucide-static/package.json'), 'utf8')).version;
const morphVersion = JSON.parse(readFileSync(join(here, 'node_modules/morphicons/package.json'), 'utf8')).version;

/** Lucide SVG text -> IconNode ([tag, attrs] list). Lucide files are one element per line, so a small parser is enough. */
function parseSvg(text) {
  const nodes = [];
  for (const m of text.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g)) {
    const attrs = {};
    for (const a of m[2].matchAll(/([\w-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    nodes.push([m[1], attrs]);
  }
  if (nodes.length === 0) throw new Error('no drawable elements');
  return nodes;
}

const nodes = {};
for (const name of spec.icons) nodes[name] = parseSvg(readFileSync(join(here, 'node_modules/lucide-static/icons', `${name}.svg`), 'utf8'));
// Icons the mockup draws by hand (tools/wide-boards/shell.js): the same 24-grid, 2-unit round stroke as Lucide, kept as drawn so the app matches the boards.
const custom = spec.custom ?? {};
for (const [name, paths] of Object.entries(custom)) nodes[name] = paths.map((d) => ['path', { d }]);

const camel = (name) => name.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
const round = (n) => Math.round(n * 100) / 100;
const preset = SPRING_PRESETS[spec.preset];
if (!preset) throw new Error(`unknown spring preset ${spec.preset}`);

/**
 * Spring position x(t) at a fixed 1/240 s step. The clip ends when the spring is within 0.5% of its target: the last
 * 0.5% (a long tail, about 0.2 s for "smooth") cannot be seen and would only make the icon feel slow to finish.
 * The last keyframe is the exact end shape.
 */
function runSpring() {
  const sp = new Spring();
  sp.config(preset.k, preset.c);
  sp.start();
  const dt = 1 / 240;
  const xs = [0];
  let t = 0;
  while (t < 5) {
    sp.step(dt);
    t += dt;
    xs.push(sp.x);
    if (Math.abs(1 - sp.x) < 0.005) break;
  }
  return { xs, dt, settle: t };
}
const { xs, dt, settle } = runSpring();

function bake(pair) {
  const plan = buildPlan(resampleIcon(nodes[pair.from], spec.points), resampleIcon(nodes[pair.to], spec.points));
  const closed = plan.items.map((it) => it.closed);
  const out = allocOutputs(plan);
  const frames = [];
  for (let i = 0; i <= spec.keyframes; i++) {
    const time = (settle * i) / spec.keyframes;
    const x = i === 0 ? 0 : i === spec.keyframes ? 1 : xs[Math.min(xs.length - 1, Math.round(time / dt))];
    interpPolar(plan, x, out);
    frames.push(out.flatMap((a) => Array.from(a, round)).join(' '));
  }
  // The same plan gives every frame the same subpaths and point count, so the frames are interchangeable by construction.
  const perFrame = plan.items.length * plan.n * 2;
  for (const f of frames) if (f.split(' ').length !== perFrame) throw new Error(`${pair.name}: frame size mismatch`);
  return { plan, closed, frames };
}

const lines = [];
lines.push('// GENERATED by android/app/tools/icon-morph/generate.mjs. Do not edit by hand: change icons.json and run `npm run generate`.');
lines.push(`// Icons: Lucide ${lucideVersion} (ISC, https://lucide.dev). Morphs: Morphicons ${morphVersion} (MIT), preset "${spec.preset}" (k=${preset.k}, c=${preset.c}).`);
lines.push('package shelftap.android.ui.icons', '');
lines.push('/** Lucide icons as path data on a 24 x 24 grid, drawn with a 2-unit round stroke. */');
lines.push('object LucideIcons {');
for (const name of [...spec.icons, ...Object.keys(custom)]) lines.push(`    val ${camel(name)} = "${cubicsToPathD(iconToCubics(nodes[name]))}"`);
lines.push('}', '');
lines.push('/** Spring keyframes baked by Morphicons: play linearly over [MorphSpec.durationMs]; the easing is already in the frames. */');
lines.push('object LucideMorphs {');
for (const pair of spec.pairs) {
  const { plan, closed, frames } = bake(pair);
  lines.push(`    val ${pair.name} = MorphSpec(`);
  lines.push(`        durationMs = ${Math.round(settle * 1000)}, points = ${plan.n}, closed = "${closed.map((c) => (c ? '1' : '0')).join('')}",`);
  lines.push('        frames = listOf(');
  for (const f of frames) lines.push(`            "${f}",`);
  lines.push('        ),', '    )');
}
lines.push('}', '');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join('\n'));
console.log(`wrote ${outFile}: ${spec.icons.length} icons, ${spec.pairs.length} morphs, settle ${Math.round(settle * 1000)} ms`);
